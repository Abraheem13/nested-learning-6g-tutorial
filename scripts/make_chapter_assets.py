#!/usr/bin/env python3
"""Build every number, table and data figure in the chapter from the run logs.

Nothing quantitative in ``chapter/chapter.tex`` is typed by hand. This script
recomputes each quantity from ``results/raw`` (through the experiment
manifests) and writes:

    chapter/generated/numbers.tex      one \\newcommand per number in the text
    chapter/generated/tab_*.tex        every results table
    chapter/figures/drift.pdf          Fig. 2, drawn from the simulator itself
    chapter/figures/controls.pdf       Fig. 3, drawn from the run logs
    results/chapter_numbers.json       the same numbers, machine-readable

Run it after the experiments::

    python scripts/run_experiments.py --preset full --workers 4
    python scripts/run_robustness.py --workers 4
    python scripts/run_noise_probe.py --workers 4
    python scripts/run_review_analyses.py --workers 4
    python scripts/make_chapter_assets.py

``--check`` regenerates everything in memory and compares it, byte for byte,
with the files on disk; ``scripts/verify_chapter.py`` calls it that way.

Statistics: two-sided paired permutation tests over seeds (exact enumeration),
Holm correction within each stated family, 95% percentile-bootstrap intervals
for mean paired differences. See ``nested6g/analysis/statistics.py``.
"""

