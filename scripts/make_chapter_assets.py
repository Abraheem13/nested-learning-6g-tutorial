# --------------------------------------------------------------------------- #
#  Small helpers
# --------------------------------------------------------------------------- #
class Numbers:
    """Collects named, formatted numbers; each becomes a LaTeX macro."""

    def __init__(self) -> None:
        self.values: dict[str, str] = {}

    def __setitem__(self, name: str, text: str) -> None:
        if not name.isalpha():
            raise ValueError(f"macro name must be letters only: {name!r}")
        if name in self.values and self.values[name] != text:
            raise ValueError(f"{name} set twice with different values")
        self.values[name] = text

    def tex(self) -> str:
        lines = ["% Generated by scripts/make_chapter_assets.py -- do not edit.",
                 "% Every number quoted in the chapter text is defined here."]
        for k in sorted(self.values):
            lines.append(f"\\newcommand{{\\{k}}}{{{self.values[k]}}}")
        return "\n".join(lines) + "\n"


def f2(x: float) -> str:
    return f"{x:.2f}"


def f3(x: float) -> str:
    return f"{x:.3f}"


def sg(x: float, nd: int = 2) -> str:
    """Signed value for use inside math mode."""
    return f"{x:+.{nd}f}"


def pf(p: float) -> str:
    """p-value to three decimals. At n = 10 the permutation floor 3/1025 prints
    as 0.003."""
    return f"{p:.3f}"


def summary(experiment: str, keys=("method", "seed"), root: Path = RESULTS_ROOT,
            fill: dict | None = None) -> pd.DataFrame:
    df = load_experiment(experiment, root)
    for col, default in (fill or {}).items():
        if col not in df.columns:
            df[col] = default
        df[col] = df[col].fillna(default)
    return agg.per_seed_summary(df, group_keys=keys)


def col(s: pd.DataFrame, method: str, c: str, **where) -> pd.Series:
    m = s["method"] == method
    for k, v in where.items():
        m &= s[k] == v
    return s[m].set_index("seed")[c].sort_index()


def paired(a: pd.Series, b: pd.Series, name: str = ""):
    shared = a.index.intersection(b.index)
    if len(shared) != len(a) or len(shared) != len(b):
        raise ValueError(f"unpaired seeds in {name}")
    return summarise(a.loc[shared].to_numpy(), b.loc[shared].to_numpy(), name)


def nseeds(s: pd.DataFrame, by=("method",)) -> int:
    counts = s.groupby(list(by))["seed"].nunique()
    if counts.min() != counts.max():
        raise ValueError("unequal seed counts across cells")
    return int(counts.min())


def table(lines: list[str]) -> str:
    return "\n".join(lines) + "\n"


def rate_tex(x: float) -> str:
    """1e-4 -> 10^{-4}; 5e-4 -> 5\\!\\cdot\\!10^{-4}."""
    m, e = f"{x:.0e}".split("e")
    e = int(e)
    return f"10^{{{e}}}" if m == "1" else f"{m}\\!\\cdot\\!10^{{{e}}}"


