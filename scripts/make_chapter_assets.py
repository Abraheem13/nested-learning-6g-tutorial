CHAPTER_TABLES: dict[str, str] = {}
#: Qualitative statements made in the text, each checked against the data.
CLAIMS: dict[str, bool] = {}


def build(root: Path) -> dict[Path, bytes]:
    CHAPTER_TABLES.clear()
    CLAIMS.clear()
    N, out = Numbers(), {}
    headline(N, out, root)
    ablation(N, out, root)
    tz = tuned(N, out, root)
    st = review(N, out, root)
    noise(N, out, root)
    scalability(N, out, root)
    counts(N, out, root)
    # numbers.tex carries exactly the macros the manuscript uses; the JSON keeps
    # every computed value.
    # Without the manuscript (it is not distributed before publication), every
    # computed macro is written.
    used = Numbers()
    if MANUSCRIPT.exists():
        text = MANUSCRIPT.read_text()
        letter = CHAPTER / "response" / "response.tex"
        if letter.exists():
            text += letter.read_text()
        for k, v in N.values.items():
            if re.search(rf"\\{k}(?![A-Za-z])", text):
                used[k] = v
    else:
        used.values = dict(N.values)
    files: dict[Path, bytes] = {
        CHAPTER / "generated" / "numbers.tex": used.tex().encode(),
        root / "chapter_numbers.json": (json.dumps(
            {"macros": N.values, "claims": CLAIMS, "detail": out}, indent=2,
            default=float) + "\n").encode(),
    }
    for name, text in CHAPTER_TABLES.items():
        files[CHAPTER / "generated" / name] = text.encode()
    files[CHAPTER / "figures" / "drift.pdf"] = figure_drift()
    files[CHAPTER / "figures" / "controls.pdf"] = figure_controls(tz, st)
    return files


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--results", type=Path, default=RESULTS_ROOT)
    p.add_argument("--check", action="store_true",
                   help="compare with the files on disk instead of writing")
    args = p.parse_args(argv)
    files = build(args.results)
    if args.check:
        if not MANUSCRIPT.exists():
            # Only the machine-readable numbers can be checked without the
            # manuscript; the LaTeX outputs are build products.
            files = {f: b for f, b in files.items() if f.suffix == ".json"}
        def current(f: Path, b: bytes) -> bool:
            if not f.exists():
                return False
            if f.suffix == ".json":
                # Compare the reported (formatted) numbers and the claims; the
                # unrounded detail differs in the last digits across platforms.
                old, new = json.loads(f.read_text()), json.loads(b)
                return (old["macros"], old["claims"]) == (new["macros"], new["claims"])
            return f.read_bytes() == b
        bad = [f for f, b in files.items() if not current(f, b)]
        for f in bad:
            print(f"OUT OF DATE: {f}")
        print(f"{len(files) - len(bad)} of {len(files)} generated files are current.")
        return 1 if bad else 0
    for f, b in files.items():
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_bytes(b)
        print(f"wrote {f}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
