def _pdf_bytes(fig) -> bytes:
    buf = io.BytesIO()
    fig.savefig(buf, format="pdf", metadata={"CreationDate": None, "Creator": None,
                                             "Producer": None})
    return buf.getvalue()


def figure_drift() -> bytes:
    """Fig. 2: drift bands as produced by the simulator (seed 0, kappa 1.5)."""
    plt = _style()
    from nested6g.env import EnvConfig, SliceEnv
    env = SliceEnv(EnvConfig(kappa=1.5), seed=0)
    env.reset()
    rng = np.random.default_rng(0)
    T = 400
    chan, dem, reg = [], [], []
    for _ in range(T):
        st = env.drift.state            # state at time t, then advance
        chan.append(float(st.channel[0, 0]))
        dem.append(st.demand.copy())
        reg.append(int(st.regime))
        env.step(rng.integers(0, env.n_actions, size=env.cfg.n_agents))
    dem = np.asarray(dem)
    fig, ax = plt.subplots(3, 1, figsize=(5.6, 3.9), sharex=True)
    ax[0].plot(chan, color="0.15", lw=0.8)
    ax[0].set_ylabel("link gain")
    ax[0].set_title("Fast band: every step", loc="left")
    sty = [("-", "0.15"), ("--", "0.40"), (":", "0.0")]
    for k, (ls, c) in enumerate(sty):
        ax[1].step(range(T), dem[:, k], where="post", ls=ls, color=c, lw=1.0,
                   label=["eMBB", "URLLC", "mMTC"][k])
    ax[1].set_ylabel("demand mult.")
    ax[1].legend(ncol=3, loc="lower right", bbox_to_anchor=(1.0, 0.98),
                 handlelength=2.2, columnspacing=1.0)
    ax[1].set_title(rf"Medium band: every $\tau_{{\mathrm{{med}}}}={env.cfg.tau_med}$ steps",
                    loc="left")
    ax[2].step(range(T), reg, where="post", color="0.15", lw=1.1)
    ax[2].set_yticks(range(env.cfg.n_regimes))
    ax[2].set_yticklabels([rf"$\rho_{r}$" for r in range(env.cfg.n_regimes)])
    ax[2].set_ylabel("SLA regime")
    ax[2].set_xlabel("environment step $t$")
    ax[2].set_xlim(0, T)
    ax[2].set_title(rf"Slow band: every $\tau_{{\mathrm{{slow}}}}={env.cfg.tau_slow}$ steps",
                    loc="left")
    fig.tight_layout()
    b = _pdf_bytes(fig)
    plt.close(fig)
    return b


