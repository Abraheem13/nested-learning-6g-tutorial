def headline(N: Numbers, out: dict, root: Path) -> None:
    s = summary("headline", root=root)
    n = nseeds(s)
    N["nSeeds"] = str(n)
    order = [("ippo", r"IPPO ($\alpha{=}5\!\cdot\!10^{-4}$)"), ("mappo", "MAPPO"),
             ("ewc_ippo", "EWC-IPPO"), ("nested_marl", r"Nested-MARL")]
    cols = ["reward_first40", "reward_all80", "reward_last20", "sla_last30",
            "switching_last30"]
    means = {m: {c: col(s, m, c).mean() for c in cols + ["queue_last30"]}
             for m, _ in order}
    rows = []
    for m, label in order:
        v = means[m]
        cells = [f2(v["reward_first40"]), f2(v["reward_all80"]),
                 f2(v["reward_last20"]), f3(v["sla_last30"]),
                 f3(v["switching_last30"])]
        if m == "nested_marl":
            label = r"\textbf{" + label + "}"
            best = {c: max(means[x][c] for x, _ in order) for c in cols}
            low_sw = min(means[x]["switching_last30"] for x, _ in order)
            for i, c in enumerate(cols[:3]):
                if v[c] == best[c]:
                    cells[i] = r"\textbf{" + cells[i] + "}"
            if v["switching_last30"] == low_sw:
                cells[4] = r"\textbf{" + cells[4] + "}"
        rows.append(" & ".join([label] + cells) + r" \\")
    CHAPTER_TABLES["tab_headline.tex"] = table([
        r"\begin{table}[tb]", r"\centering",
        r"\caption{Comparison against the conventional baseline rate, "
        rf"$\kappa{{=}}1.5$, $n{{=}}{n}$ seeds. Reward is averaged over the stated "
        r"episode window; SLA and switching cost over the last 30 episodes.}",
        r"\label{tab:headline}", r"\footnotesize",
        r"\begin{tabular}{lrrrrr}", r"\toprule",
        r"Method & First-40 & All-80 & Last-20 & SLA & Switching \\", r"\midrule",
        *rows, r"\bottomrule", r"\end{tabular}", r"\end{table}"])

    nest, ippo = means["nested_marl"], means["ippo"]
    N["headIppoFirst"] = f2(ippo["reward_first40"])
    N["headNestFirst"] = f2(nest["reward_first40"])
    # Holm family: nested vs the three baselines, first-40 reward.
    res = {m: paired(col(s, "nested_marl", "reward_first40"),
                     col(s, m, "reward_first40"), m)
           for m in ("ippo", "mappo", "ewc_ippo")}
    holm = holm_bonferroni({m: r.p_value for m, r in res.items()})
    N["headGainPct"] = f"{res['ippo'].delta_pct:.1f}"
    N["headGainPholm"] = pf(holm["ippo"])
    churn = 100 * (ippo["switching_last30"] - nest["switching_last30"]) / ippo["switching_last30"]
    N["headChurnPct"] = f"{churn:.1f}"
    N["headChurnP"] = pf(paired(col(s, "nested_marl", "switching_last30"),
                                col(s, "ippo", "switching_last30")).p_value)
    # Operating point: are SLA and backlog distinguishable between methods?
    op_p = []
    for c in ("sla_last30", "queue_last30"):
        r = {m: paired(col(s, "nested_marl", c), col(s, m, c), m).p_value
             for m in ("ippo", "mappo", "ewc_ippo")}
        op_p += list(holm_bonferroni(r).values())
    qs = [means[m]["queue_last30"] for m, _ in order]
    sl = [means[m]["sla_last30"] for m, _ in order]
    N["opQueueLo"], N["opQueueHi"] = f"{min(qs):.1f}", f"{max(qs):.1f}"
    N["opSlaLo"], N["opSlaHi"] = f3(min(sl)), f3(max(sl))
    N["opMinPholm"] = f"{min(op_p):.2f}"
    out["headline"] = {"means": means, "p_holm": holm,
                       "operating_point_min_p_holm": min(op_p)}


def ablation(N: Numbers, out: dict, root: Path) -> None:
    s = summary("ablation_powered", root=root)
    n = nseeds(s)
    N["ablSeeds"] = str(n)
    last = {m: col(s, m, "reward_last30").mean() for m in
            ("ippo", "nested_marl", "nested_same_rate", "nested_two_timescale",
             "nested_no_ema")}
    N["ablNestLast"] = f2(last["nested_marl"])
    N["ablSameLast"] = f2(last["nested_same_rate"])
    N["ablIppoLast"] = f2(last["ippo"])
    N["ablTwoLast"] = f2(last["nested_two_timescale"])
    # Holm family: full method vs each ablation and IPPO, last-30 reward.
    fam = ("ippo", "nested_same_rate", "nested_two_timescale", "nested_no_ema")
    res = {m: paired(col(s, "nested_marl", "reward_last30"),
                     col(s, m, "reward_last30"), m) for m in fam}
    holm = holm_bonferroni({m: r.p_value for m, r in res.items()})
    N["ablSamePholm"] = pf(holm["nested_same_rate"])
    N["ablTwoPholm"] = pf(holm["nested_two_timescale"])
    # Is the same-rate control really below IPPO? Separate paired test.
    r = paired(col(s, "nested_same_rate", "reward_last30"),
               col(s, "ippo", "reward_last30"), "same_vs_ippo")
    N["ablSameVsIppoP"] = pf(r.p_value)
    res40 = {m: paired(col(s, "nested_marl", "reward_first40"),
                       col(s, m, "reward_first40"), m) for m in fam}
    holm40 = holm_bonferroni({m: r.p_value for m, r in res40.items()})
    N["ablSameFirst"] = f2(col(s, "nested_same_rate", "reward_first40").mean())
    N["ablSameFirstPholm"] = pf(holm40["nested_same_rate"])
    CLAIMS["same-rate control below IPPO on last-30 (p < 0.05)"] = bool(
        r.delta < 0 and r.p_value < 0.05)
    first = {m: col(s, m, "reward_first40").mean() for m in ("nested_marl", "nested_no_ema")}
    N["ablNoEmaFirst"] = f2(first["nested_no_ema"])
    N["ablNestFirst"] = f2(first["nested_marl"])
    out["ablation"] = {"last30": last, "p_holm_last30": holm,
                       "same_vs_ippo_p": r.p_value, "first40": first}


def tuned(N: Numbers, out: dict, root: Path) -> dict:
    s = summary("matched_budget", root=root)
    n = nseeds(s)
    single = [m for m in METHODS if m.startswith("ippo_lr")]
    single = [m for m in single if m in set(s["method"])]
    nested = [m for m in NESTED_CONFIGS if m in set(s["method"])]
    m40 = {m: col(s, m, "reward_first40").mean() for m in single + nested}
    best_single = max(single, key=m40.get)
    best_nested = max(nested, key=m40.get)
    ref = "nested_cfg_original"
    lr = {m: METHODS[m].learning_rates[0] for m in single}

    rows = []
    entries = sorted([(m40[m], m) for m in single] + [(m40[ref], ref)], reverse=True)
    for _, m in entries:
        f40 = col(s, m, "reward_first40").mean()
        l20 = col(s, m, "reward_last20").mean()
        sw = col(s, m, "switching_last30").mean()
        if m == ref:
            label = "Nested-MARL (reference config)"
        else:
            label = rf"IPPO, $\alpha={rate_tex(lr[m])}$"
            if lr[m] == 5e-4:
                label += r" \emph{(conventional)}"
        cells = [f2(f40), f2(l20), f3(sw)]
        if m == best_single:
            cells[0] = r"\textbf{" + cells[0] + "}"
        best_l20 = max(col(s, x, "reward_last20").mean() for x in single + [ref])
        if l20 == best_l20:
            cells[1] = r"\textbf{" + cells[1] + "}"
        low_sw = min(col(s, x, "switching_last30").mean() for x in single + [ref])
        if sw == low_sw:
            cells[2] = r"\textbf{" + cells[2] + "}"
        rows.append(" & ".join([label] + cells) + r" \\")
    CHAPTER_TABLES["tab_tuned.tex"] = table([
        r"\begin{table}[tb]", r"\centering",
        r"\caption{Control 1: baseline learning-rate sweep, $\kappa{=}1.5$, "
        rf"$n{{=}}{n}$ seeds. Switching over the last 30 episodes.}}",
        r"\label{tab:tuned}", r"\footnotesize",
        r"\begin{tabular}{lrrr}", r"\toprule",
        r"Method & First-40 & Last-20 & Switching \\", r"\midrule",
        *rows, r"\bottomrule", r"\end{tabular}", r"\end{table}"])

    # Control 1 text: best single-rate vs the reference nested config.
    r1 = paired(col(s, best_single, "reward_first40"), col(s, ref, "reward_first40"))
    N["tunedBestFirst"] = f2(m40[best_single])
    N["tunedBestRate"] = rate_tex(lr[best_single])
    N["tunedBestVsRefP"] = pf(r1.p_value)
    second = sorted(single, key=m40.get)[-2]
    r1b = paired(col(s, second, "reward_first40"), col(s, ref, "reward_first40"))
    N["tunedSecondRate"] = rate_tex(lr[second])
    N["tunedSecondFirst"] = f2(m40[second])
    N["tunedSecondVsRefP"] = pf(r1b.p_value)
    CLAIMS["best single-rate beats reference nested on first-40 and last-20"] = bool(
        m40[best_single] > m40[ref] and col(s, best_single, "reward_last20").mean()
        > col(s, ref, "reward_last20").mean() and r1.p_value < 0.05)
    CLAIMS["second single-rate beats reference nested on first-40 and last-20"] = bool(
        m40[second] > m40[ref] and col(s, second, "reward_last20").mean()
        > col(s, ref, "reward_last20").mean() and r1b.p_value < 0.05)

    # Control 2: matched budget.
    r2 = paired(col(s, best_nested, "reward_first40"), col(s, best_single, "reward_first40"))
    N["mbBestNestFirst"] = f2(m40[best_nested])
    N["mbBestNestTriple"] = ",".join(rate_tex(x) for x in METHODS[best_nested].learning_rates)
    N["mbDelta"] = f2(r2.delta)
    N["mbDeltaPct"] = f"{r2.delta_pct:.1f}"
    N["mbP"] = pf(r2.p_value)
    rc = paired(col(s, best_nested, "switching_last30"), col(s, best_single, "switching_last30"))
    N["mbChurnNest"] = f3(rc.mean_a)
    N["mbChurnSingle"] = f3(rc.mean_b)
    N["mbChurnP"] = f"{rc.p_value:.2f}"
    out["tuned"] = {"first40": m40, "best_single": best_single,
                    "best_nested": best_nested, "best_vs_ref_p": r1.p_value,
                    "matched_delta": r2.delta, "matched_p": r2.p_value}
    return {"m40": m40, "lr": lr, "single": single, "nested": nested,
            "best_single": best_single, "best_nested": best_nested, "n": n}


def review(N: Numbers, out: dict, root: Path) -> dict:
    st = json.loads((root / "review_stats.json").read_text())

    # ---- A. partition -----------------------------------------------------
    A = st["partition"]
    n = A["n_seeds"]
    label = {"depth": "Depth (hand-designed)", "inverted": "Inverted depth",
             "random": "Random, equal sizes", "grad_snr": "Gradient SNR (data-driven)"}
    rows = []
    for k in ("depth",) + PARTITION_KINDS:
        cells = [label[k]]
        for t in PARTITION_TRIPLES:
            v = A[t][k]
            if k == "depth":
                cells += [f2(v["reward_first40"]), "---", "---"]
            else:
                cells += [f2(v["reward_first40"]), f"${sg(v['reward_first40_delta'])}$",
                          pf(v["reward_first40_p_holm"])]
        rows.append(" & ".join(cells) + r" \\")
    CHAPTER_TABLES["tab_partition.tex"] = table([
        r"\begin{table}[tb]", r"\centering",
        r"\caption{Partition sensitivity: first-40 reward, $\kappa{=}1.5$, "
        rf"$n{{=}}{n}$ seeds. $\Delta$ and Holm-corrected $p$ are against the "
        r"depth partition at the same rates.}",
        r"\label{tab:partition}", r"\footnotesize",
        r"\begin{tabular}{lrrrrrr}", r"\toprule",
        r" & \multicolumn{3}{c}{Reference rates} & \multicolumn{3}{c}{Tuned rates} \\",
        r"\cmidrule(lr){2-4}\cmidrule(lr){5-7}",
        r"Partition & Reward & $\Delta$ & $p$ & Reward & $\Delta$ & $p$ \\", r"\midrule",
        *rows, r"\bottomrule", r"\end{tabular}", r"\end{table}"])
    names = {"ref": "Ref", "tuned": "Tuned"}
    kn = {"inverted": "Inv", "random": "Rand", "grad_snr": "Snr"}
    for t in PARTITION_TRIPLES:
        for k in PARTITION_KINDS:
            N[f"part{names[t]}{kn[k]}Delta"] = sg(A[t][k]["reward_first40_delta"])
        N[f"part{names[t]}MaxP"] = pf(max(A[t][k]["reward_first40_p_holm"]
                                         for k in PARTITION_KINDS))
        g = A[t]["grad_snr"]
        n_agents = g["n_assignments"] // 12          # 12 tensors per network
        N[f"part{names[t]}SnrHeadFast"] = str(g["fast_counts"].get("actor.4.weight", 0))
        N["partSnrAgents"] = str(n_agents)
        CLAIMS[f"every alternative partition is worse than depth ({t} rates)"] = all(
            A[t][k]["reward_first40_delta"] < 0 and A[t][k]["reward_first40_p_holm"] < 0.05
            and A[t][k]["reward_last20_delta"] < 0 for k in PARTITION_KINDS)
    N["partRefDepth"] = f2(A["ref"]["depth"]["reward_first40"])
    N["partRefSnrAgree"] = f"{100 * A['ref']['grad_snr']['agreement']:.0f}"
    N["partLastMaxP"] = pf(max(A[t][k]["reward_last20_p_holm"]
                               for t in PARTITION_TRIPLES for k in PARTITION_KINDS))
    CLAIMS["SNR agreement with depth is near chance (< 50%)"] = all(
        A[t]["grad_snr"]["agreement"] < 0.5 for t in PARTITION_TRIPLES)
    CLAIMS["best partition at reference rates still below best single-rate IPPO"] = bool(
        A["ref"]["depth"]["reward_first40"] < max(
            v for m, v in out["tuned"]["first40"].items() if m.startswith("ippo")))

    # ---- B. severity and band separation ----------------------------------
    B = st["scope"]
    n = B["n_seeds"]
    rows = []
    keys = [f"k{k:g}_ts50" for k in B["kappas"]] + \
           [f"k1.5_ts{t}" for t in B["taus"] if t != 50]
    for key in keys:
        c, t = B["conventional"][key], B["tuned"][key]
        if key.endswith("_ts50"):
            lab = rf"$\kappa{{=}}{c['kappa']:g}$"
            if c["kappa"] == 0:
                lab += " (stationary)"
        else:
            lab = rf"$\kappa{{=}}1.5$, $\tau_{{\mathrm{{slow}}}}{{=}}{c['tau_slow']}$"
        rows.append(f"{lab} & ${sg(c['delta'])}$ & ${sg(c['delta_pct'], 1)}$ & "
                    f"{pf(c['p'])} & ${sg(t['delta'])}$ & {pf(t['p'])} \\\\")
        if key == f"k{B['kappas'][-1]:g}_ts50":
            rows.append(r"\midrule")
    CHAPTER_TABLES["tab_scope.tex"] = table([
        r"\begin{table}[tb]", r"\centering",
        r"\caption{Nested minus single-rate first-40 reward across drift severity "
        r"($\tau_{\mathrm{slow}}{=}50$) and band separation ($\tau_{\mathrm{med}}{=}15$), "
        rf"$n{{=}}{n}$ seeds, unadjusted $p$. Conventional: reference configuration "
        r"vs IPPO at $5\!\cdot\!10^{-4}$; tuned: best of five each.}",
        r"\label{tab:scope}", r"\footnotesize",
        r"\begin{tabular}{lrrrrr}", r"\toprule",
        r" & \multicolumn{3}{c}{Conventional} & \multicolumn{2}{c}{Tuned} \\",
        r"\cmidrule(lr){2-4}\cmidrule(lr){5-6}",
        r"Condition & $\Delta$ & $\Delta\%$ & $p$ & $\Delta$ & $p$ \\", r"\midrule",
        *rows, r"\bottomrule", r"\end{tabular}", r"\end{table}"])
    N["scopeSeeds"] = str(n)
    word = {0.0: "Zero", 0.5: "Half", 1.0: "One", 1.5: "OneHalf", 2.0: "Two"}
    for k in B["kappas"]:
        c, t = B["conventional"][f"k{k:g}_ts50"], B["tuned"][f"k{k:g}_ts50"]
        N[f"convK{word[k]}Delta"] = sg(c["delta"])
        N[f"convK{word[k]}Pct"] = f"{c['delta_pct']:.1f}"
        N[f"convK{word[k]}P"] = pf(c["p"])
        N[f"tunedK{word[k]}Delta"] = sg(t["delta"])
        N[f"tunedK{word[k]}P"] = pf(t["p"])
    oos = [B["tuned"][f"k{k:g}_ts50"]["delta"] for k in B["kappas"] if k != 1.5]
    N["tunedOosMean"] = sg(float(np.mean(oos)))
    conv = [B["conventional"][f"k{k:g}_ts50"]["delta"] for k in B["kappas"] if k > 0]
    N["convDriftDeltaLo"], N["convDriftDeltaHi"] = f2(min(conv)), f2(max(conv))
    tw = {16: "Coll", 150: "Wide"}
    for tau in B["taus"]:
        if tau == 50:
            continue
        for nm, short in (("conventional", "conv"), ("tuned", "tuned")):
            v = B[nm][f"k1.5_ts{tau}"]
            N[f"{short}Ts{tw[tau]}Delta"] = sg(v["delta"])
            N[f"{short}Ts{tw[tau]}P"] = pf(v["p"])
            d = B[nm][f"did_ts{tau}"]
            N[f"{short}Did{tw[tau]}"] = sg(d["delta"])
            N[f"{short}Did{tw[tau]}P"] = pf(d["p"])
    conv_cells = [v for k, v in B["conventional"].items() if not k.startswith("did")]
    tuned_cells = {k: v for k, v in B["tuned"].items() if not k.startswith("did")}
    CLAIMS["conventional advantage positive and significant in every cell"] = all(
        v["delta"] > 0 and v["p"] < 0.05 for v in conv_cells)
    CLAIMS["conventional advantage does not depend on band separation"] = all(
        B["conventional"][f"did_ts{t}"]["p"] > 0.05 for t in B["taus"] if t != 50)
    CLAIMS["tuned advantage not significant outside the selection cell"] = all(
        v["p"] > 0.05 for k, v in tuned_cells.items() if k != "k1.5_ts50")
    CLAIMS["conventional relative advantage falls from kappa 0.5 to 2"] = bool(
        B["conventional"]["k0.5_ts50"]["delta_pct"] > B["conventional"]["k2_ts50"]["delta_pct"])
    out["review"] = st
    return st


def noise(N: Numbers, out: dict, root: Path) -> None:
    s = summary("noise_probe", keys=("method", "noise", "seed"), root=root,
                fill={"noise": 0.10})
    s["noise"] = s["noise"].round(4)
    n = nseeds(s, ("method", "noise"))
    methods = ("ippo_lr0p005", "ippo_lr0p002", "nested_marl")
    rows, gaps = [], {}
    for lv in sorted(s["noise"].unique()):
        means = {m: (col(s, m, "reward_first40", noise=lv).mean(),
                     col(s, m, "reward_last20", noise=lv).mean()) for m in methods}
        best_e = max(v[0] for v in means.values())
        best_l = max(v[1] for v in means.values())
        cells = []
        for m in methods:
            e, l = means[m]
            es = r"\textbf{" + f"{e:.1f}" + "}" if e == best_e else f"{e:.1f}"
            ls = r"\textbf{" + f"{l:.1f}" + "}" if l == best_l else f"{l:.1f}"
            cells.append(f"{es} / {ls}")
        tag = " (default)" if lv == 0.10 else ""
        rows.append(f"{lv:.2f}{tag} & " + " & ".join(cells) + r" \\")
        r = paired(col(s, "nested_marl", "reward_first40", noise=lv),
                   col(s, "ippo_lr0p005", "reward_first40", noise=lv))
        gaps[lv] = r
    CHAPTER_TABLES["tab_noise.tex"] = table([
        r"\begin{table}[tb]", r"\centering",
        r"\caption{Control 4: channel noise and demand jitter scaled together to "
        rf"three and five times their default ($n{{=}}{n}$ seeds; first-40 / "
        r"last-20 reward).}",
        r"\label{tab:noise}", r"\footnotesize", r"\setlength{\tabcolsep}{9pt}",
        r"\begin{tabular}{lrrr}", r"\toprule",
        r"Noise std. & IPPO $5\!\cdot\!10^{-3}$ & IPPO $2\!\cdot\!10^{-3}$ & Nested-MARL \\",
        r"\midrule", *rows, r"\bottomrule", r"\end{tabular}", r"\end{table}"])
    lv = sorted(gaps)
    N["noiseGapDefault"] = sg(gaps[lv[0]].delta)
    N["noiseGapMid"] = sg(gaps[lv[1]].delta)
    N["noiseGapHigh"] = sg(gaps[lv[2]].delta)
    N["noiseGapDefaultPct"] = f"{gaps[lv[0]].delta_pct:.1f}"
    N["noiseGapHighPct"] = f"{gaps[lv[2]].delta_pct:.1f}"
    N["noiseGapMaxP"] = pf(max(g.p_value for g in gaps.values()))
    CLAIMS["tuned single-rate leads at every noise level (p < 0.05)"] = all(
        g.delta < 0 and g.p_value < 0.05 for g in gaps.values())
    CLAIMS["shortfall does not close as noise grows"] = bool(
        abs(gaps[lv[2]].delta) >= abs(gaps[lv[0]].delta))
    CLAIMS["relative shortfall widens from default to highest noise"] = bool(
        gaps[lv[2]].delta_pct < gaps[lv[0]].delta_pct)
    # The default-noise runs are the default-environment runs: the first row
    # must reproduce the baseline sweep exactly.
    CLAIMS["noise-probe default row equals the baseline-sweep cells"] = bool(
        abs(col(s, "ippo_lr0p005", "reward_first40", noise=0.10).mean()
            - out["tuned"]["first40"]["ippo_lr0p005"]) < 1e-9)
    out["noise"] = {str(k): {"delta": g.delta, "delta_pct": g.delta_pct, "p": g.p_value}
                    for k, g in gaps.items()}


def scalability(N: Numbers, out: dict, root: Path) -> None:
    s = summary("scalability", keys=("method", "n_agents", "n_slices", "seed"), root=root)
    n = nseeds(s, ("method", "n_agents", "n_slices"))
    N["scaleSeeds"] = str(n)
    res = {}
    for na, w in ((3, "Three"), (6, "Six"), (10, "Ten")):
        a = col(s, "nested_marl", "reward_first40", n_agents=na, n_slices=3)
        b = col(s, "ippo", "reward_first40", n_agents=na, n_slices=3)
        pct = 100 * (a.mean() - b.mean()) / b.mean()
        N[f"scale{w}Pct"] = f"{pct:.1f}"
        res[na] = pct
    out["scalability"] = res


def counts(N: Numbers, out: dict, root: Path) -> None:
    used = ("headline", "ablation_powered", "matched_budget", "tuned_baseline",
            "severity", "stationary_control", "tuned_stationary", "scalability",
            "noise_probe", "review_partition", "review_scope")
    runs: dict[tuple, dict] = {}
    for e in used:
        for r in json.loads((root / "manifests" / f"{e}.json").read_text())["runs"]:
            # Some registry names are aliases of the same algorithm (e.g. IPPO at
            # 5e-4 under two names); count each distinct computation once.
            m = METHODS[r["method"]]
            sig = (m.learning_rates, m.ema_lambda, m.stabilise_beta,
                   m.centralised_critic, m.ewc_lambda, getattr(m, "partition", "depth"))
            key = (sig, r["seed"], r["episodes"], r["kappa"], r["n_agents"],
                   r["n_slices"], r["horizon"], r.get("tau_slow", 50),
                   r.get("noise", 0.10))
            runs[key] = r
    steps = sum(r["episodes"] * r["horizon"] * r["n_agents"] for r in runs.values())
    N["nRuns"] = f"{len(runs):,}".replace(",", "{,}")
    N["nAgentSteps"] = f"{steps / 1e6:.1f}"
    out["counts"] = {"runs": len(runs), "agent_steps": steps}


