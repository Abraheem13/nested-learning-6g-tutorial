#!/usr/bin/env python3
"""Build the submission: a single self-contained chapter compiled in svmult.

The working manuscript (``chapter/chapter.tex``) takes every number from
``chapter/generated/numbers.tex`` and every table from ``chapter/generated/``.
For submission these are flattened into one ``chapter.tex`` with the values
written in, so that production editors receive ordinary LaTeX.

    python scripts/build_chapter.py            # build + page count
    python scripts/build_chapter.py --zip      # also write the submission zip

Output in ``chapter/submission/``:

    author.tex      svmult main file (\\documentclass[graybox]{svmult})
    chapter.tex     the flattened chapter
    references.bib
    figures/        drift.pdf, controls.pdf
    svmult.cls, spbasic.bst   Springer class and style, for compiling only
    author.pdf      the compiled chapter

Requires pdflatex and bibtex (TeX Live).
"""

from __future__ import annotations

import argparse
import re
import shutil
import subprocess
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CH = ROOT / "chapter"
OUT = CH / "submission"
PAGE_LIMIT = 18

AUTHOR_TEX = r"""\documentclass[graybox]{svmult}
\usepackage{mathptmx}
\usepackage{helvet}
\usepackage{courier}
\usepackage{type1cm}
\usepackage{makeidx}
\usepackage{graphicx}
\usepackage{multicol}
\usepackage[bottom]{footmisc}
\usepackage{amsmath,amssymb}
\usepackage{booktabs}
\usepackage{natbib}
\usepackage{url}
\usepackage{algorithm}
\usepackage{algpseudocode}
\usepackage{tikz}
\usetikzlibrary{arrows.meta,positioning,fit,backgrounds,calc}
\makeindex
\begin{document}
\input{chapter}
\bibliographystyle{spbasic}
\bibliography{references}
\end{document}
"""


def flatten(tex: str) -> str:
    """Inline generated tables and the TikZ figure; substitute number macros."""
    macros = dict(re.findall(r"\\newcommand\{\\([A-Za-z]+)\}\{(.*)\}",
                             (CH / "generated" / "numbers.tex").read_text()))

    def inline(m: re.Match) -> str:
        path = CH / (m.group(1) + ".tex")
        body = path.read_text().rstrip("\n")
        return body

    tex = re.sub(r"^\\input\{generated/numbers\}\s*\n", "", tex, flags=re.M)
    tex = re.sub(r"\\input\{((?:generated|figures)/[A-Za-z_]+)\}", inline, tex)
    for name in sorted(macros, key=len, reverse=True):
        val = macros[name]
        tex = re.sub(rf"\\{name}(?![A-Za-z])(\{{\}})?", lambda _m, v=val: v, tex)
    left = re.findall(r"\\([a-z]+[A-Z][A-Za-z]*)", tex)
    left = [x for x in left if x in macros]
    if left:
        raise RuntimeError(f"unsubstituted macros: {left}")
    header = ("% Flattened by scripts/build_chapter.py from chapter/chapter.tex and\n"
              "% chapter/generated/ -- every number below is generated from the run logs.\n")
    return header + tex


def write_labels() -> None:
    """Export the chapter's section/table/figure numbers for the response letter,
    so the letter cannot cite a stale section number."""
    aux = (OUT / "author.aux").read_text(errors="replace")
    lines = ["% Generated by scripts/build_chapter.py from the compiled chapter."]
    for lab, num in re.findall(r"\\newlabel\{((?:sec|tab|fig):[^}]+)\}\{\{([^}]*)\}", aux):
        name = "ref" + "".join(w.capitalize() for w in re.split(r"[^A-Za-z]+", lab) if w)
        lines.append(f"\\newcommand{{\\{name}}}{{{num}}}")
    (CH / "response").mkdir(exist_ok=True)
    (CH / "response" / "labels.tex").write_text("\n".join(lines) + "\n")


def build_letter() -> bool:
    d = CH / "response"
    if not (d / "response.tex").exists():
        return True
    for _ in range(2):
        subprocess.run(["pdflatex", "-interaction=nonstopmode", "response"], cwd=d,
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    log = (d / "response.log").read_text(errors="replace")
    bad = re.findall(r"^! .*|Undefined control sequence|Reference .* undefined", log, re.M)
    for f in d.glob("response.*"):
        if f.suffix not in (".tex", ".pdf"):
            f.unlink()
    print(f"response letter: {'OK' if not bad else 'ERRORS ' + str(bad[:3])}")
    return not bad


def run(cmd: list[str]) -> None:
    subprocess.run(cmd, cwd=OUT, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--zip", action="store_true")
    args = p.parse_args(argv)
    if not (CH / "chapter.tex").exists():
        print("Manuscript not found at chapter/chapter.tex: it is not distributed "
              "with the code before publication. Nothing to build.")
        return 0

    if OUT.exists():
        shutil.rmtree(OUT)
    (OUT / "figures").mkdir(parents=True)
    (OUT / "chapter.tex").write_text(flatten((CH / "chapter.tex").read_text()))
    (OUT / "author.tex").write_text(AUTHOR_TEX)
    shutil.copy(CH / "references.bib", OUT)
    for f in ("drift.pdf", "controls.pdf"):
        shutil.copy(CH / "figures" / f, OUT / "figures")
    for f in ("svmult.cls", "spbasic.bst"):
        shutil.copy(CH / "springer" / f, OUT)

    for cmd in (["pdflatex", "-interaction=nonstopmode", "author"], ["bibtex", "author"],
                ["pdflatex", "-interaction=nonstopmode", "author"],
                ["pdflatex", "-interaction=nonstopmode", "author"]):
        run(cmd)
    log = (OUT / "author.log").read_text(errors="replace")
    errors = re.findall(r"^! .*", log, flags=re.M)
    undefined = re.findall(r"(Citation|Reference) `([^']+)' .*undefined", log)
    overfull = re.findall(r"Overfull \\hbox \(([\d.]+)pt too wide\)", log)
    info = subprocess.run(["pdfinfo", "author.pdf"], cwd=OUT, capture_output=True,
                          text=True).stdout
    pages = int(re.search(r"Pages:\s+(\d+)", info).group(1)) if "Pages" in info else -1
    print(f"pages: {pages} (limit {PAGE_LIMIT}, including references)")
    print(f"LaTeX errors: {len(errors)}  undefined refs/cites: {len(undefined)}  "
          f"overfull boxes > 1pt: {sum(float(x) > 1 for x in overfull)}")
    for m in re.finditer(r"Overfull \\hbox \(([\d.]+)pt too wide\) (.*)", log):
        if float(m.group(1)) > 1:
            print(f"   overfull {m.group(1)}pt {m.group(2)}")
    for e in errors[:10]:
        print("  ", e)
    for u in undefined[:10]:
        print("   undefined:", u)
    ok = pages != -1 and pages <= PAGE_LIMIT and not errors and not undefined
    write_labels()
    for aux in OUT.glob("author.*"):
        if aux.suffix not in (".tex", ".pdf"):
            aux.unlink()

    ok = build_letter() and ok
    if args.zip:
        z = CH / "chapter-submission.zip"
        with zipfile.ZipFile(z, "w", zipfile.ZIP_DEFLATED) as zf:
            for f in sorted(OUT.rglob("*")):
                if f.is_file():
                    zf.write(f, Path("chapter-submission") / f.relative_to(OUT))
        print(f"wrote {z.relative_to(ROOT)}")
    print("BUILD OK" if ok else "BUILD FAILED")
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
